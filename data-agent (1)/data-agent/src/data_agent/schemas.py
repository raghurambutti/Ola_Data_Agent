"""
Pydantic models used as LangGraph state and as Claude structured outputs
(ported from the tutorial's `Models/schema.py`).
"""

from operator import add
from typing import Annotated, Literal

from pydantic import BaseModel, Field


# ----------------------------- SQL Analyst ---------------------------------
class AgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(
        default_factory=list, description="Messages exchanged inside the SQL Analyst"
    )
    user_question: str = Field(..., description="The original question asked by the user")
    curated_ques: str = Field("", description="Curated user question")
    prompt_query_context: str = Field(
        "", description="Prompt with DB schema context used to generate the SQL query"
    )
    generated_sql_query: str = Field("", description="The SQL query generated by Claude")
    is_safe: Literal["Yes", "No"] = Field(
        "No", description="Whether the generated SQL query is safe to execute"
    )
    comments: str = Field("", description="The judge's comments on the SQL query")
    sql_query_execution_result: str = Field(
        "", description="The result of executing the SQL query on the database"
    )
    final_answer: str = Field("", description="The final answer shown to the user")


class JudgeSchema(BaseModel):
    """Verdict of the 'LLM as a judge' SQL safety check."""

    answer: Literal["Yes", "No"] = Field(
        ..., description="'Yes' if the SQL query is read-only and safe to execute, otherwise 'No'"
    )
    comments: str = Field(..., description="Short explanation of the decision")


# ----------------------------- ETL Analyst ---------------------------------
class ETLAgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(
        default_factory=list, description="Messages exchanged inside the ETL Analyst"
    )


# ----------------------------- Data Agent (router) -------------------------
class RouterSchema(BaseModel):
    """Which sub-agent should handle the user's request."""

    answer: Literal["sql", "etl"] = Field(
        ...,
        description=(
            "'sql' for questions answered by querying the ride-sharing PostgreSQL database; "
            "'etl' for extracting data from an API/URL or transforming data files"
        ),
    )
    comments: str = Field(..., description="Short reason for the routing decision")


class DataAgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(
        default_factory=list, description="Conversation messages handled by the Data Agent"
    )
    route_response: str = Field("", description="'sql' or 'etl', chosen by the router")
    route_comments: str = Field("", description="Why the router chose that route")
    final_answer: str = Field("", description="The answer returned to the user")
    generated_sql_query: str = Field("", description="SQL query used, when routed to SQL")
